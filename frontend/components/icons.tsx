export function SourceTypeIcon({ type, className }: { type: "url" | "pdf" | "youtube"; className?: string }) {
  if (type === "pdf") return <PdfIcon className={className} />;
  if (type === "youtube") return <YoutubeIcon className={className} />;
  return <LinkIcon className={className} />;
}
